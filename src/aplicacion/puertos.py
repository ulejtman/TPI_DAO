from typing import Protocol
from src.dominio.reglas import Inventario


class RepositorioInventario(Protocol):
    def obtener(self, producto_id: int, ubicacion_id: int) -> Inventario: ...
    def guardar(self, producto_id: int, ubicacion_id: int, inventario: Inventario) -> None: ...


class UnidadDeTrabajo(Protocol):
    def __enter__(self): ...
    def __exit__(self, exc_type, exc_value, traceback): ...
